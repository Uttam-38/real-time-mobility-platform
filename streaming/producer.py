import json
import time
from datetime import datetime, timezone

from kafka import KafkaProducer
from kafka.errors import KafkaError

from ingestion.fetch_live_data import fetch_vehicle_data
from validation.validate_vehicle import validate_vehicle


VALID_TOPIC = "vehicle-positions"
DLQ_TOPIC = "vehicle-positions-dlq"


producer = KafkaProducer(
    bootstrap_servers="localhost:9092",
    value_serializer=lambda value: json.dumps(value).encode("utf-8")
)


while True:

    try:

        vehicles = fetch_vehicle_data()

        valid_count = 0
        invalid_count = 0

        for vehicle in vehicles:

            # Add metadata generated by our pipeline
            vehicle["ingestion_timestamp"] = datetime.now(
                timezone.utc
            ).isoformat()

            vehicle["source"] = "valley_metro"

            # Validate the vehicle record
            errors = validate_vehicle(vehicle)

            try:

                if errors:

                    dlq_record = {
                        "original_record": vehicle,
                        "validation_errors": errors,
                        "failed_at": datetime.now(
                            timezone.utc
                        ).isoformat()
                    }

                    producer.send(
                        DLQ_TOPIC,
                        value=dlq_record
                    )

                    invalid_count += 1

                else:

                    producer.send(
                        VALID_TOPIC,
                        value=vehicle
                    )

                    valid_count += 1

            except KafkaError as error:

                print(
                    "Kafka send error:",
                    vehicle.get("vehicle_id"),
                    error
                )

        producer.flush()

        print(f"Valid records sent: {valid_count}")
        print(f"Invalid records sent to DLQ: {invalid_count}")
        print("-" * 60)

    except Exception as error:

        print(
            "Error while fetching or processing data:",
            error
        )

    time.sleep(15)